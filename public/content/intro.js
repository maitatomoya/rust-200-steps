<li><strong>開発スピードは出しにくい場面がある</strong>：コンパイルが通るまで書き切る必要があるため、「とりあえず動かして試す」探索的な開発にはPythonなどの方が速いことが多い。</li>
<li><strong>コンパイル時間が長め</strong>：大きなプロジェクトではビルド待ちが発生しやすい。</li>
<li><strong>人材・情報がまだ少ない</strong>：JavaやPHPと比べると、日本語の情報や経験者の数は発展途上。</li>
